import { useState, useEffect } from 'react';
import { Login } from './pages/Login';
import { Home } from './pages/Home';
import { Generator } from './pages/Generator';
import { MyDesigns } from './pages/MyDesigns';
import type { DesignState } from './types/house';
import { getMe, saveDesign, updateDesign, deleteDesign } from './services/api';

export type ViewState = 'login' | 'home' | 'generator' | 'my-designs';

function App() {
    const [view, setView] = useState<ViewState>('login');
    const [isAuthenticated, setIsAuthenticated] = useState(false);
    const [user, setUser] = useState<any>(null);
    const [isAppLoading, setIsAppLoading] = useState(true);
    
    const [designState, setDesignState] = useState<DesignState | null>(null);

    useEffect(() => {
        const verifyAuth = async () => {
            const token = localStorage.getItem('ai_house_token');
            if (token) {
                try {
                    const me = await getMe();
                    setUser(me);
                    setIsAuthenticated(true);
                    setView('home');
                } catch (err) {
                    // Token invalid or expired
                    localStorage.removeItem('ai_house_token');
                }
            }
            setIsAppLoading(false);
        };
        verifyAuth();
    }, []);

    const handleLogin = (token: string, userData: any) => {
        localStorage.setItem('ai_house_token', token);
        setUser(userData);
        setIsAuthenticated(true);
        setView('home');
    };

    const handleLogout = () => {
        localStorage.removeItem('ai_house_token');
        setIsAuthenticated(false);
        setUser(null);
        setDesignState(null);
        setView('login');
    };

    const handleSaveDesign = async (design: DesignState) => {
        try {
            // Check if this is a newly generated design or an existing one
            // If it hasn't been saved to the DB yet, it won't exist there, but the frontend generator assigns a UUID.
            // We should use saveDesign (POST) if it's new, or updateDesign (PUT) if it already exists.
            // For simplicity, the backend assigns a new ID on POST.
            
            // Map frontend DesignState to backend DesignCreate schema
            const payload = {
                name: design.name,
                prompt: design.prompt,
                requirements_json: design.requirements,
                layout_json: design.layout,
                floorplan_json: design.floorplan,
                // CRITICAL: Embed renders into house3d_json so it persists across DB saves
                house3d_json: { ...design.scene, __renders: design.renders }
            };

            // Assuming if we already saved it, the backend assigned an ID which we kept in state
            // But we can't easily know if the current UUID was generated by frontend or backend
            // Let's assume if it is a new generation, we do POST. If the user clicks Save again, we do PUT.
            // Let's check if the ID is a valid backend ID (we'll just use the backend's returned ID)
            // Actually, wait, let's just POST if we don't have a backend ID tracked.
            // Since we don't track that cleanly without modifying design state, let's always POST for now,
            // or if the user modifies an opened design, PUT.
            
            let savedDBDesign;
            if (design.id.startsWith('temp-') || !design.id.includes('-')) {
                // It's newly generated or we need to POST
                savedDBDesign = await saveDesign(payload);
            } else {
                try {
                    savedDBDesign = await updateDesign(design.id, payload);
                } catch (e: any) {
                    if (e.message.includes('404')) {
                        savedDBDesign = await saveDesign(payload);
                    } else {
                        throw e;
                    }
                }
            }

            // Update designState with the real backend ID and timestamps
            setDesignState({
                ...design,
                id: savedDBDesign.id,
                createdAt: new Date(savedDBDesign.created_at).getTime(),
                updatedAt: new Date(savedDBDesign.updated_at).getTime(),
            });

            alert('Design saved successfully!');
        } catch (error) {
            console.error(error);
            alert('Failed to save design.');
        }
    };

    const handleDeleteDesign = async (id: string) => {
        try {
            await deleteDesign(id);
            if (designState?.id === id) {
                setDesignState(null);
            }
            // Trigger refresh in MyDesigns (handled via state in MyDesigns or passing a prop)
            return true;
        } catch (error) {
            console.error(error);
            alert('Failed to delete design.');
            return false;
        }
    };

    if (isAppLoading) {
        return (
            <div className="min-h-screen bg-slate-50 flex items-center justify-center">
                <div className="animate-spin rounded-full h-12 w-12 border-b-2 border-blue-600"></div>
            </div>
        );
    }

    if (!isAuthenticated) {
        return <Login onLogin={handleLogin} />;
    }

    const renderView = () => {
        switch (view) {
            case 'home':
                return <Home onNavigate={setView} />;
            case 'generator':
                return (
                    <Generator 
                        designState={designState}
                        setDesignState={setDesignState}
                        onSaveDesign={handleSaveDesign}
                    />
                );
            case 'my-designs':
                return (
                    <MyDesigns 
                        onOpenDesign={(design) => {
                            setDesignState(design);
                            setView('generator');
                        }}
                        onDeleteDesign={handleDeleteDesign}
                        onNavigate={setView}
                    />
                );
            default:
                return <Home onNavigate={setView} />;
        }
    };

    return (
        <div className="min-h-screen bg-slate-50 flex flex-col font-sans">
            {/* Global Header */}
            <header className="bg-white border-b border-slate-200 px-8 py-5 flex justify-between items-center shadow-sm relative z-10">
                <div className="flex items-center gap-8">
                    <div>
                        <h1 className="text-xl font-bold tracking-tight text-slate-800">AI Text-to-3D House</h1>
                    </div>
                    <nav className="hidden md:flex items-center gap-6 text-sm font-medium">
                        <button onClick={() => setView('home')} className={`transition-colors ${view === 'home' ? 'text-blue-600' : 'text-slate-500 hover:text-slate-800'}`}>Home</button>
                        <button onClick={() => setView('my-designs')} className={`transition-colors ${view === 'my-designs' ? 'text-blue-600' : 'text-slate-500 hover:text-slate-800'}`}>My Designs</button>
                        <button 
                            onClick={() => {
                                setDesignState(null);
                                setView('generator');
                            }} 
                            className={`transition-colors ${view === 'generator' ? 'text-blue-600' : 'text-slate-500 hover:text-slate-800'}`}
                        >
                            New Design
                        </button>
                    </nav>
                </div>
                <div className="flex items-center gap-6">
                    <div className="hidden sm:flex items-center gap-2 text-sm text-slate-500">
                        <span className="w-2 h-2 rounded-full bg-green-500"></span>
                        {user?.email || 'User'}
                    </div>
                    <button 
                        onClick={handleLogout}
                        className="text-sm font-medium text-slate-500 hover:text-slate-800 transition-colors"
                    >
                        Sign Out
                    </button>
                </div>
            </header>

            {/* Main View Content */}
            <main className="flex-1 flex overflow-hidden">
                {renderView()}
            </main>
        </div>
    );
}

export default App;
